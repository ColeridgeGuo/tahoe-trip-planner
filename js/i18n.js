export function makeT(lang) {
  const dict = STR[lang] || STR.zh;
  return (key, vars) => {
    let s = key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
    if (s == null) return key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
